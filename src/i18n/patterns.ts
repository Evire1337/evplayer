// Texts the app builds from parts ("6 треков", "Добавлено в «Любимое»"): a pattern for each,
// with a function that writes the English one. `piece` translates a part that is itself text.

export type Piece = (text: string) => string;
export type Pattern = [RegExp, (m: RegExpExecArray, piece: Piece) => string];

const n = (value: string) => Number(value.replace(/\s| /g, ""));
const count = (value: string, one: string, many: string) => `${value} ${n(value) === 1 ? one : many}`;

export const EN_PATTERNS: Pattern[] = [
  // counts
  [/^(\d[\d\s ]*) трек(?:а|ов)?$/, (m) => count(m[1], "track", "tracks")],
  [/^(\d[\d\s ]*) прослушивани(?:е|я|й)$/, (m) => count(m[1], "play", "plays")],
  [/^(\d[\d\s ]*) слушател(?:ь|я|ей)$/, (m) => count(m[1], "listener", "listeners")],
  [/^(\d[\d\s ]*) процесс\(ов\) приложения(.*)$/, (m, piece) => `${m[1]} app process(es)${m[2].trim() ? " " + piece(m[2].trim().replace(/^,\s*/, "")) : ""}`],
  [/^(\d[\d\s ]*) подписчик(?:а|ов)? на SoundCloud$/, (m) => `${m[1]} followers on SoundCloud`],
  [/^(\d[\d\s ]*) подписчик(?:а|ов)? на YouTube$/, (m) => `${m[1]} subscribers on YouTube`],
  [/^(\d[\d\s ]*) слушател(?:ь|я|ей) в месяц$/, (m) => `${m[1]} monthly listeners`],
  [/^(\d[\d\s ]*) в ваших файлах$/, (m) => `${m[1]} in your files`],
  [/^у вас (.+)$/, (m, piece) => `you have ${piece(m[1])}`],
  [/^вы: (.+)$/, (m) => `you: ${m[1]}`],
  [/^Умный · (.+)$/, (m, piece) => `Smart · ${piece(m[1])}`],
  // units
  [/^(\d+) с$/, (m) => `${m[1]} s`],
  [/^(\d+) мин$/, (m) => `${m[1]} min`],
  [/^(\d+) ч (\d+) мин$/, (m) => `${m[1]} h ${m[2]} min`],
  [/^(\d+) мин (\d+) с$/, (m) => `${m[1]} min ${m[2]} s`],
  [/^([\d.,]+) МБ(.*)$/, (m, piece) => `${m[1]} MB${m[2].trim() ? " " + piece(m[2].trim()) : ""}`],
  [/^([\d.,]+) КБ$/, (m) => `${m[1]} KB`],
  [/^< 1 КБ$/, () => "< 1 KB"],
  [/^([\d.,]+) Гц$/, (m) => `${m[1]} Hz`],
  [/^([\d.,]+) кГц$/, (m) => `${m[1]} kHz`],
  [/^([+−-]?[\d.,]+) дБ$/, (m) => `${m[1]} dB`],
  [/^(\d+) полос: перетаскивайте точки на графике вверх-вниз \(громкость\) и влево-вправо \(частота\)$/, (m) => `${m[1]} bands: drag the points on the chart up and down (volume) and left and right (frequency)`],
  [/^(.+) — пауза, (.+) \/ (.+) — треки, (.+) — нравится, (.+) — спрятать$/, (m, piece) => `${piece(m[1])} — pause, ${m[2]} / ${m[3]} — songs, ${m[4]} — like, ${m[5]} — hide`],
  [/^(\d+) КБ$/, (m) => `${m[1]} KB`],
  [/^([+−-]?[\d.,]+) с$/, (m) => `${m[1]} s`],
  [/^([+−-]?[\d.,]+) пт$/, (m) => `${m[1]} st`],
  [/^сдвиг (.+)$/, (m, piece) => `shift ${piece(m[1])}`],
  [/^(\d+) дн\.?$/, (m) => `${m[1]} d`],
  // lists and names
  [/^Плейлист · (.+)$/, (m, piece) => `Playlist · ${piece(m[1])}`],
  [/^Альбом · (.+)$/, (m) => `Album · ${m[1]}`],
  [/^Плейлист из (.+)$/, (m) => `Playlist from ${m[1]}`],
  [/^Альбом из (.+)$/, (m) => `Album from ${m[1]}`],
  [/^· создан (.+)$/, (m) => `· created ${m[1]}`],
  [/^создан (.+)$/, (m) => `created ${m[1]}`],
  [/^· скачано (\d+) из (\d+)$/, (m) => `· downloaded ${m[1]} of ${m[2]}`],
  [/^скачано (\d+) из (\d+)$/, (m) => `downloaded ${m[1]} of ${m[2]}`],
  [/^· найдено (\d+)$/, (m) => `· found ${m[1]}`],
  [/^(\d+) из (\d+)(.*)$/, (m, piece) => `${m[1]} of ${m[2]}${m[3].trim() ? " " + piece(m[3].trim()) : ""}`],
  [/^Исполнитель: (.+)$/, (m) => `Artist: ${m[1]}`],
  [/^Полоса (\d+)$/, (m) => `Band ${m[1]}`],
  [/^Исполнитель · (.+)$/, (m) => `Artist · ${m[1]}`],
  [/^Похоже на «(.+)»$/, (m) => `Similar to "${m[1]}"`],
  [/^Добавлено в «(.+)»$/, (m) => `Added to "${m[1]}"`],
  [/^Уже есть в «(.+)»$/, (m) => `Already in "${m[1]}"`],
  [/^Плейлист «(.+)» создан$/, (m) => `Playlist "${m[1]}" created`],
  [/^«(.+)» сохранён в библиотеку$/, (m) => `"${m[1]}" saved to the library`],
  [/^Убрать «(.+)» из истории$/, (m) => `Remove "${m[1]}" from history`],
  [/^Организатор: (.+)$/, (m) => `Host: ${m[1]}`],
  [/^Вместе: (.+)$/, (m, piece) => `Together: ${piece(m[1])}`],
  [/^Слушаете вместе: (.+)$/, (m) => `Listening together: ${m[1]}`],
  [/^Исключить (.+)$/, (m) => `Remove ${m[1]}`],
  [/^Цвет (.+)$/, (m) => `Colour ${m[1]}`],
  [/^Отправить (.+)$/, (m) => `Send ${m[1]}`],
  // downloads
  [/^Докачать остальное \((\d+)\)$/, (m) => `Download the rest (${m[1]})`],
  [/^Скачиваю: (\d+)$/, (m) => `Downloading: ${m[1]}`],
  [/^Скачиваю для офлайн: (.+)$/, (m, piece) => `Downloading for offline: ${piece(m[1])}`],
  [/^Скачать (\d+ трек.*)$/, (m, piece) => `Download ${piece(m[1])}`],
  [/^Удалено копий: (\d+)$/, (m) => `Copies deleted: ${m[1]}`],
  [/^Сохранено (\d+) из (\d+)\. Не получилось: (\d+)(.*)$/, (m) => `Saved ${m[1]} of ${m[2]}. Failed: ${m[3]}`],
  [/^Для офлайн сохранено: (\d+)$/, (m) => `Saved for offline: ${m[1]}`],
  [/^не получилось: (\d+)$/, (m) => `failed: ${m[1]}`],
  [/^(\d+) из (\d+) · (\d+)%$/, (m) => `${m[1]} of ${m[2]} · ${m[3]}%`],
  // updates
  [/^Скачиваю (\S+): (\d+)%$/, (m) => `Downloading ${m[1]}: ${m[2]}%`],
  [/^Версия (\S+) готова — установится при перезапуске$/, (m) => `Version ${m[1]} is ready — it installs on restart`],
  [/^Версия (.*)$/, (m) => `Version ${m[1]}`],
  [/^Не получилось проверить: (.+)$/, (m) => `Could not check: ${m[1]}`],
  // sessions and diagnostics
  [/^Сервис отвечает медленно · нет изменений (.+)$/, (m, piece) => `The service is slow · no change for ${piece(m[1])}`],
  [/^Идёт загрузка · (.+)$/, (m, piece) => `Loading · ${piece(m[1])}`],
  [/^Сейчас: (.+)$/, (m) => `Now: ${m[1]}`],
  [/^(\d+)% занят$/, (m) => `${m[1]}% busy`],
  [/^(\d+) кадр\/с$/, (m) => `${m[1]} fps`],
  [/^Следующий трек вступает за (\d+) с до конца текущего$/, (m) => `The next song comes in ${m[1]} s before the end of this one`],
  [/^Версия (.+) · /, (m) => `Version ${m[1]} · `],
  [/^Всё, что сейчас есть в EvPlayer на этом компьютере, заменится содержимым копии от (.*)\.$/, (m) => `Everything in EvPlayer on this computer will be replaced by the backup of ${m[1]}.`],
  [/^Играет (.+)$/, (m) => `Playing ${m[1]}`],
  [/^Повтор: (трек|вся очередь|выключен)$/, (m, piece) => `Repeat: ${piece(m[1])}`],
  [/^(.+): меньше$/, (m, piece) => `${piece(m[1])}: less`],
  [/^(.+): больше$/, (m, piece) => `${piece(m[1])}: more`],
];
